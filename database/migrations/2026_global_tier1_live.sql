-- Keep old player IDs and admin boosts stable on every deployment.
INSERT INTO players (name,team,position,overall,region,tier,season,image_url)
SELECT r.name,r.team,r.position,r.overall,r.region,
  CASE WHEN r.overall<=80 THEN 'COMMON' WHEN r.overall<=90 THEN 'RARE'
       WHEN r.overall<=100 THEN 'EPIC' ELSE 'LEGENDARY' END,
  r.season,NULL
FROM tmp_2026_global_live r
WHERE NOT EXISTS (
  SELECT 1 FROM players p WHERE p.name=r.name AND p.team=r.team
    AND p.position=r.position AND p.season=r.season
);
DROP TEMPORARY TABLE tmp_2026_global_live;

-- Audit teams and player counts across the entire Tier-1 2026 circuit.
SELECT region,COUNT(DISTINCT team) AS teams,COUNT(*) AS live_cards
FROM players WHERE season='26 LIVE'
GROUP BY region ORDER BY FIELD(region,'LCK','LPL','LEC','LCS','CBLOL','LCP');
