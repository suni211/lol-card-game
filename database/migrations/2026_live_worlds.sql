USE lol_card_game;

-- Retain the old LTA enumeration for archived cards, but enable 2026 LCS + CBLOL.
ALTER TABLE players MODIFY COLUMN region
  ENUM('LCK','LTA','LPL','LEC','LCP','LCS','CBLOL') NOT NULL;

CREATE TABLE IF NOT EXISTS worlds2026_live_boosts (
  player_id INT PRIMARY KEY,
  base_overall INT NOT NULL,
  boost_amount INT NOT NULL DEFAULT 0,
  achievement VARCHAR(255) DEFAULT NULL,
  evidence_url VARCHAR(500) DEFAULT NULL,
  updated_by INT DEFAULT NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (player_id) REFERENCES players(id) ON DELETE CASCADE,
  FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS worlds2026_boost_history (
  id INT PRIMARY KEY AUTO_INCREMENT,
  player_id INT NOT NULL,
  previous_boost INT NOT NULL,
  new_boost INT NOT NULL,
  previous_overall INT NOT NULL,
  new_overall INT NOT NULL,
  achievement VARCHAR(255) NOT NULL,
  evidence_url VARCHAR(500) DEFAULT NULL,
  changed_by INT NOT NULL,
  changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_worlds2026_history_player (player_id),
  FOREIGN KEY (player_id) REFERENCES players(id) ON DELETE CASCADE,
  FOREIGN KEY (changed_by) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

