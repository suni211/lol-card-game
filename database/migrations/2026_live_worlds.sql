INSERT INTO players (name,team,position,overall,region,tier,season,image_url)
SELECT s.name,s.team,s.position,s.overall,s.region,s.tier,s.season,s.image_url
FROM tmp_2026_roster s
WHERE NOT EXISTS (
  SELECT 1 FROM players p
  WHERE p.name=s.name AND p.team=s.team AND p.position=s.position AND p.season=s.season
);

INSERT INTO worlds2026_live_boosts (player_id,base_overall,boost_amount)
SELECT p.id,p.overall,0 FROM players p
LEFT JOIN worlds2026_live_boosts b ON b.player_id=p.id
WHERE p.season='26WRs' AND b.player_id IS NULL;

