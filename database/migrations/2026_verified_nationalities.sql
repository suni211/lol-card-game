SELECT season,COUNT(*) AS total,
  SUM(nationality IS NOT NULL AND TRIM(nationality) <> '') AS assigned,
  SUM(nationality IS NULL OR TRIM(nationality) = '') AS unassigned
FROM players WHERE season IN ('26 LIVE','26WR','26WRs')
GROUP BY season ORDER BY season;
